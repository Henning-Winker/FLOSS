# Guide: the app's own plain-language guide (inst/app/guide/app-guide.md),
# the workflow diagram, a teaching introduction and the settings explained.
# The website article inst/guide/how-it-works.md is not used here and keeps
# its R code for package users.

# The guide's sections, named by their "## " heading (e.g. "4. Sampling").
# Tabs pick sections by heading, so adding a section never moves another.
guide_sections <- function() {
  f <- c(file.path("guide", "app-guide.md"),
         system.file("app", "guide", "app-guide.md", package = "FLOSS"))
  f <- f[nzchar(f) & file.exists(f)][1]
  if (is.na(f)) return(list())
  x <- readLines(f, warn = FALSE, encoding = "UTF-8")
  starts <- grep("^## ", x)
  ends <- c(starts[-1] - 1, length(x))
  secs <- Map(function(a, b) paste(x[a:b], collapse = "\n"), starts, ends)
  names(secs) <- sub("^## +", "", x[starts])
  secs
}

md_html <- function(txt) HTML(commonmark::markdown_html(txt, extensions = TRUE))

# The sections whose heading matches one of the patterns, in that order
guide_pick <- function(s, patterns) {
  hit <- unlist(lapply(patterns, function(p) grep(p, names(s), ignore.case = TRUE)))
  div(class = "guide", md_html(paste(unlist(s[unique(hit)]), collapse = "\n\n")))
}

guide_ui <- function() {
  s <- guide_sections()
  tabsetPanel(
    id = "guide_tabs",
    tabPanel("Start here",
      box(width = 12, title = "What FLOSS is for",
        p("FLOSS simulates fisheries whose true dynamics are known, together with the data an observer would collect from them. ",
          "It is designed for teaching population dynamics and the interpretation of fisheries data: users predict how a stock will respond to a change, ",
          "examine the response both in the true stock and in the simulated data, and learn to recognise warning flags, which are patterns in data that real stock dynamics cannot produce."),
        p("The app neither uses nor requires real data. Every stock history is generated by FLOSS from the settings users enter, ",
          "over a hypothetical period (by default 1969 to 2025) that begins close to unfished conditions. ",
          "These years label an imaginary fishery, so the simulation creates a plausible past for that fishery rather than forecasting the future of a real stock. ",
          "Because FLOSS creates the stock, its true status is always known, and conclusions drawn from the simulated data can be checked against reality in a way no real fishery allows. ",
          "Each iteration repeats the same history with different random recruitment and effort noise, showing how far outcomes can vary through chance alone.")),
      box(width = 12, title = "How a FLOSS run is built",
        p("Each run is built in layers, which follow the numbered steps in the left panel (steps marked * are required):"),
        tags$ol(
          tags$li(tags$strong("Fishery: "), "the fleets, the years simulated, and each fleet's fishing effort over time, which is shared by every species the fleet catches."),
          tags$li(tags$strong("Species: "), "each species' life history, target maximum sustainable yield (MSY), and selectivity and catchability by fleet."),
          tags$li(tags$strong("Operating model: "), "the true, age-structured dynamics of each stock, built with the Build operating model button."),
          tags$li(tags$strong("Sampling: "), "the data an observer would collect, namely catch, effort, catch per unit effort (CPUE), survey indices, length samples, and biological samples, drawn with the Sample data button."),
          tags$li(tags$strong("Treatments (optional): "), "a single change to the operating model, whether to fishing effort, recruitment, selectivity, effort creep, or natural mortality, run against an untreated baseline that shares every random number, so any difference between the two results from the treatment alone."),
          tags$li(tags$strong("Export: "), "one dataset per iteration, with a separate answer key holding the true dynamics."),
          tags$li(tags$strong("True status (optional, for trainers): "), "the answer key, shown only when Hide truth is unticked.")),
        div(class = "workflow",
            tags$img(src = "floss-workflow.svg",
                     alt = "How the FLOSS steps connect: Fishery, Species, and Operating model lead to Sampling and Export; Treatments is an optional branch from the operating model that uses the sampling settings; True status shows the answer key.")),
        p(class = "note", "Solid arrows show the path through the app; dashed arrows show settings or results one step borrows from another.")),
      box(width = 12, title = "Predict first",
        div(class = "predictbox",
          p("Users set up a fishery and its stocks: the fleets and how their fishing effort changes over time, each species' life history (growth, maturity, natural mortality, and recruitment), ",
            "each fleet's selectivity and catchability, and the way data are collected (which years, how many fish are measured, and the error in each data stream). ",
            "From these inputs, FLOSS simulates two things: the true history of each stock (spawning biomass, fishing mortality, catch, and recruitment relative to MSY reference points), ",
            "and the data an observer would record (catch, effort, CPUE, survey indices, length frequencies, and biological samples)."),
          p(style = "margin-bottom:0;",
            "Before running each step, users should predict what the outputs will show, for example whether spawning biomass will fall when effort doubles, or whether mean length will reveal the change, and how quickly. ",
            "After running the simulation, they compare the result with their prediction. The Treatments step formalises this process by asking for a prediction before revealing the outcome."))),
      box(width = 12, title = "Warning flags, Hide truth, and scope",
        div(class = "flagbox", tags$strong("Warning flags. "),
          "Some patterns in data cannot arise from real stock dynamics: an index that keeps rising while catches fall under steady effort, mean length jumping in a single year, or fish older than the plus group. ",
          "FLOSS can plant such problems deliberately in the Sampling step, and the answer key lists every problem planted."),
        div(class = "formatbox", tags$strong("Hide truth. "),
          "Hide truth is unticked when the app opens, so the truth is shown: the True status step, the true lines on the data plots, and the answer key in the export. ",
          "Trainers should tick it before showing the app to trainees, so that trainees see the data alone."),
        p(tags$strong("Scope. "),
          "FLOSS describes stock dynamics and the data they generate; it does not fit stock assessment models. ",
          "Fitting follows afterwards, for example with length-based methods in FLicc or surplus production models in JABBA, using the exported datasets, ",
          "with the answer key used to judge how well each assessment recovered the true status."),
        p(class = "note", "Structure inspired by Haddon, M. (2021) Using R for Modelling and Quantitative Methods in Fisheries. CRC Press."))),
    tabPanel("How it works", box(width = 12, guide_pick(s, c("^1\\.", "^2\\.", "^3\\.")))),
    tabPanel("Sampling and size data", box(width = 12, guide_pick(s, "^4\\."))),
    tabPanel("Treatments", box(width = 12, guide_pick(s, "^5\\."))),
    tabPanel("Warning flags", box(width = 12, guide_pick(s, "^Warning flags"))),
    tabPanel("Truth and export", box(width = 12, guide_pick(s, c("^6\\.", "^7\\.")))),
    tabPanel("Settings explained",
      box(width = 12, title = "What each setting means",
        tableOutput("guide_tips"),
        p(class = "note", "The same texts appear when you hover over the (i) symbols.")))
  )
}

