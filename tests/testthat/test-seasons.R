test_that("season designs and shares", {
  expect_equal(season_design()$share, rep(0.25, 4))
  d <- season_design(share = c(2, 1, 1, 0), shift = list(from = 2020, share = c(0, 0, 1, 1)))
  sh <- FLOSS:::season_shares(d, 2018:2021)
  expect_equal(unname(sh["2018", ]), c(0.5, 0.25, 0.25, 0))
  expect_equal(unname(sh["2021", ]), c(0, 0, 0.5, 0.5))
  expect_equal(sum(FLOSS:::split_n(37, c(0.5, 0.25, 0.25, 0))), 37)
  set.seed(1)
  r <- FLOSS:::season_shares(season_design(kappa = 5), 2000:2009)
  expect_true(all(abs(rowSums(r) - 1) < 1e-12))
  expect_error(season_design(share = c(1, 1)))
  fr <- FLOSS:::season_catch_frac(c(0.2, 1, 2), 4)
  expect_equal(rowSums(fr), c(1, 1, 1))
  expect_true(all(fr[, 1] >= fr[, 4]))
})

test_that("seasonal samples have seasons and later seasons have larger fish", {
  skip_on_cran()
  sp <- load_species("lutjanus_bohar")
  f <- load_fishery()
  om <- build_om(sp, f, nsim = 4, seed = 1)
  d <- sample_data(om, reef_oem(lfd_ess_len = 2000, lfd_ess_age = 200), iters = 1:2)
  expect_true(all(c("season") %in% names(d$lfd)))
  expect_setequal(unique(d$lfd$season[d$lfd$source != "survey"]), 1:4)
  l <- d$lfd[d$lfd$source == "linefish", ]
  ml <- tapply(l$len_mm * l$n, l$season, sum) / tapply(l$n, l$season, sum)
  expect_gt(ml[4], ml[1])
  a <- lfd_annual(d$lfd)
  expect_false("season" %in% names(a))
  expect_equal(sum(a$n), sum(d$lfd$n))
  d1 <- sample_data(om, reef_oem(seasons = season_design(1)), iters = 1)
  expect_setequal(unique(d1$lfd$season[d1$lfd$source != "survey"]), 1)
  o <- reef_oem(seasons = list(linefish = season_design(share = c(1, 0, 0, 0))))
  d2 <- sample_data(om, o, iters = 1)
  expect_setequal(unique(d2$lfd$season[d2$lfd$source == "linefish"]), 1)
  expect_true("imbalanced seasonal sampling" %in% planted_artefacts(o, f)$artefact)
  expect_true(inherits(plot_seasons(d, sp$species, 1), "ggplot"))
})

