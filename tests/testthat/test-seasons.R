test_that("gradual shift, sampling intensity and missing years", {
  d <- season_design(share = c(1, 0, 0, 0), shift = list(from = 2020, share = c(0, 0, 0, 1), over = 3))
  sh <- FLOSS:::season_shares(d, 2019:2023)
  expect_equal(unname(sh[, 1]), c(1, 0.75, 0.5, 0.25, 0))
  m <- FLOSS:::season_n_mult(season_design(n_mult = list(from = 2020, mult = 0.2)), 2019:2021)
  expect_equal(unname(m), c(1, 0.2, 0.2))
  set.seed(2)
  m2 <- FLOSS:::season_n_mult(season_design(p_missing = 0.5), 2000:2099)
  expect_true(any(m2 == 0) && any(m2 == 1))
  expect_equal(FLOSS:::scale_n(300, 0.001), 1)
  expect_equal(FLOSS:::scale_n(300, 0), 0)
  skip_on_cran()
  om <- build_om(load_species("siganus_sutor"), load_fishery(), nsim = 2, seed = 3)
  o <- reef_oem(seasons = season_design(n_mult = list(from = 2020, mult = 0.2)))
  x <- sample_data(om, o, iters = 1)
  l <- x$lfd[x$lfd$source == "linefish", ]
  n <- tapply(l$n, l$year, sum)
  expect_equal(as.numeric(n[c("2019", "2021")]), c(500, 100))
  expect_true("change in sampling intensity" %in% planted_artefacts(o)$artefact)
})
